
from __future__ import annotations

import os
import re
from collections.abc import Callable
from dataclasses import dataclass, field

from config import SEARCH_TEMPLATE_PATH, Config
from scoring import extract_answer


INFO_OPEN = "\n\n<information>"
INFO_CLOSE = "</information>\n\n"
INVALID_ACTION_MSG = (
    "\nMy previous action is invalid. If I want to search, I should put the query between "
    "<search> and </search>. If I want to give the final answer, I should put the answer "
    "between <answer> and </answer>. Let me try again.\n"
)
STOP_STRINGS = ["</search>", "</answer>"]
_ACTION_RE = re.compile(r"<(search|answer)>(.*?)</\1>", re.DOTALL)  # official pattern


def parse_action(turn_text: str) -> tuple[str | None, str]:
    """First complete <search>...</search> or <answer>...</answer> in one turn's text."""
    match = _ACTION_RE.search(turn_text)
    if match is None:
        return None, ""
    return match.group(1), match.group(2).strip()


DIRECT_TEMPLATE = (
    "Answer the given question directly, without explanation. Provide only the final "
    "answer inside <answer> and </answer>. For example, <answer> Beijing </answer>. "
    "Question: {question}\n"
)


@dataclass
class Trajectory:
    """One rollout for one question. Shared by evaluation and training.

    response_ids holds everything after the prompt: tokens generated by the
    policy plus tokens we inserted (<information> blocks, retry messages).
    loss_mask has the same length: 1 = generated by the policy (trained on),
    0 = inserted by the environment (context only, excluded from the loss).
    """
    qid: str
    question: str
    golden_answers: list[str]
    prompt_ids: list[int]
    sample_idx: int = 0                     # position within a GRPO group
    response_ids: list[int] = field(default_factory=list)
    loss_mask: list[int] = field(default_factory=list)
    n_turns: int = 0                        # generation calls made
    n_searches: int = 0                     # searches actually executed
    finish: str = ""                        # "answer" | "stop" | "length" | "max_turns"
    response_text: str = ""                 # decoded response_ids, for scoring and logs
    prediction: str | None = None           # filled by scoring.score_trajectory
    reward: float = 0.0                     # EM, filled by scoring.score_trajectory
    rollout_logprobs: list[float] = field(default_factory=list)  # vLLM's, same length as
                                            # response_ids (0.0 on inserted tokens); training only


def load_search_template() -> str:
    """The authors' exact template (written by data.py), else paper Table 1."""
    if os.path.exists(SEARCH_TEMPLATE_PATH):
        with open(SEARCH_TEMPLATE_PATH, encoding="utf-8") as f:
            return f.read()
    from data import PAPER_SEARCH_TEMPLATE
    return PAPER_SEARCH_TEMPLATE


def build_prompt_ids(tokenizer, question: str, template: str) -> list[int]:
    """Fill the template, wrap it as a single user turn, and tokenize.

    Rendering to text first (tokenize=False) and then tokenizing keeps this
    independent of how apply_chat_template's tokenize=True return type changes
    across transformers versions.
    """
    content = template.replace("{question}", question)
    text = tokenizer.apply_chat_template(
        [{"role": "user", "content": content}], tokenize=False, add_generation_prompt=True)
    return tokenizer(text, add_special_tokens=False)["input_ids"]


def make_llm(model: str, cfg: Config, gpu_memory_utilization: float,
             enable_lora: bool = False):
    """Create a vLLM engine with settings shared by evaluation and training."""
    from vllm import LLM

    kwargs = dict(
        model=model,
        dtype="bfloat16",
        max_model_len=cfg.max_model_len,
        gpu_memory_utilization=gpu_memory_utilization,
        enable_prefix_caching=True,
        seed=cfg.seed,
        generation_config="vllm",
        safetensors_load_strategy="prefetch",
    )
    if enable_lora:
        kwargs.update(enable_lora=True, max_lora_rank=cfg.lora_r, max_loras=1)
    return LLM(**kwargs)


def new_trajectories(tokenizer, questions: list[dict], template: str,
                     n_samples: int = 1) -> list[Trajectory]:
    """One Trajectory per (question, sample), grouped by question."""
    trajs = []
    for q in questions:
        prompt_ids = build_prompt_ids(tokenizer, q["question"], template)
        for k in range(n_samples):
            trajs.append(Trajectory(qid=q["id"], question=q["question"],
                                    golden_answers=q["golden_answers"],
                                    prompt_ids=prompt_ids, sample_idx=k))
    return trajs


def generate_direct(llm, tokenizer, questions: list[dict], cfg: Config,
                    lora_request=None) -> list[Trajectory]:
    """Single greedy generation per question; no retrieval."""
    from vllm import SamplingParams

    trajs = new_trajectories(tokenizer, questions, DIRECT_TEMPLATE)
    params = SamplingParams(temperature=0.0, max_tokens=cfg.direct_max_tokens)
    outputs = llm.generate([{"prompt_token_ids": t.prompt_ids} for t in trajs],
                           params, lora_request=lora_request)
    for traj, out in zip(trajs, outputs):
        completion = out.outputs[0]
        traj.response_ids = list(completion.token_ids)
        traj.loss_mask = [1] * len(traj.response_ids)
        traj.n_turns = 1
        traj.response_text = tokenizer.decode(traj.response_ids, skip_special_tokens=True)
        if extract_answer(traj.response_text) is not None:
            traj.finish = "answer"
        else:
            traj.finish = "length" if completion.finish_reason == "length" else "stop"
    return trajs


def _append(traj: Trajectory, ids: list[int], generated: bool,
            logprobs: list[float] | None = None) -> None:
    traj.response_ids.extend(ids)
    traj.loss_mask.extend([1 if generated else 0] * len(ids))
    if logprobs is None:  # NaN = "not available" for generated tokens; 0.0 for inserted ones
        logprobs = [float("nan") if generated else 0.0] * len(ids)
    traj.rollout_logprobs.extend(logprobs)


def _sampled_logprobs(completion) -> list[float] | None:
    """Logprob vLLM assigned to each sampled token, or None if unavailable."""
    if completion.logprobs is None:
        return None
    try:
        return [float(step[tok].logprob)
                for step, tok in zip(completion.logprobs, completion.token_ids)]
    except (KeyError, TypeError, AttributeError):
        return None


def generate_search(llm, tokenizer, questions: list[dict], cfg: Config,
                    search_fn: Callable[[list[str]], list[str]], n_samples: int = 1,
                    temperature: float = 0.0, lora_request=None,
                    return_logprobs: bool = False) -> list[Trajectory]:
    """Multi-turn Search-R1 rollout (paper Algorithm 1), batched across trajectories.

    Mirrors the official loop: up to `cfg.max_turns` turns in which searches are
    executed, then one final turn in which a search is not executed. Each turn:
      1. generate until </search>, </answer>, EOS, or the token budget
      2. parse the first complete <search> or <answer> block in the new text
      3. answer   -> done
         search   -> append "<information>...</information>" (masked out of the loss)
         neither  -> append the official "action is invalid" message (masked)
    Each inserted <information> block is at most `cfg.max_info_tokens` tokens,
    closing tag included. With return_logprobs=True, vLLM's logprob of every
    sampled token is kept in traj.rollout_logprobs (a training diagnostic).
    """
    from vllm import SamplingParams

    trajs = new_trajectories(tokenizer, questions, load_search_template(), n_samples)
    eos_ids = {tokenizer.eos_token_id, tokenizer.convert_tokens_to_ids("<|im_end|>")} - {None}
    info_open = tokenizer(INFO_OPEN, add_special_tokens=False)["input_ids"]
    info_close = tokenizer(INFO_CLOSE, add_special_tokens=False)["input_ids"]
    docs_budget = cfg.max_info_tokens - len(info_open) - len(info_close)
    active = list(range(len(trajs)))

    for turn in range(cfg.max_turns + 1):
        final_turn = turn == cfg.max_turns
        prompts, params, owners = [], [], []
        for i in active:
            traj = trajs[i]
            budget = min(cfg.max_gen_tokens,
                         cfg.max_model_len - len(traj.prompt_ids) - len(traj.response_ids))
            if budget <= 0:
                traj.finish = "length"
                continue
            prompts.append({"prompt_token_ids": traj.prompt_ids + traj.response_ids})
            params.append(SamplingParams(temperature=temperature, top_p=1.0, max_tokens=budget,
                                         stop=STOP_STRINGS, include_stop_str_in_output=True,
                                         logprobs=1 if return_logprobs else None))
            owners.append(i)
        if not owners:
            break

        outputs = llm.generate(prompts, params, lora_request=lora_request, use_tqdm=False)

        next_active, queries, searchers = [], [], []
        for i, out in zip(owners, outputs):
            traj = trajs[i]
            completion = out.outputs[0]
            new_ids = list(completion.token_ids)
            new_lps = _sampled_logprobs(completion) if return_logprobs else None
            action, content = parse_action(tokenizer.decode(new_ids, skip_special_tokens=True))
            traj.n_turns += 1

            if action == "answer":
                _append(traj, new_ids, generated=True, logprobs=new_lps)
                traj.finish = "answer"
            elif final_turn:
                _append(traj, new_ids, generated=True, logprobs=new_lps)
                traj.finish = "max_turns"
            elif action == "search":
                _append(traj, new_ids, generated=True, logprobs=new_lps)
                queries.append(content)
                searchers.append(i)
                next_active.append(i)
            else:
                # Drop a trailing EOS so the conversation can continue in the same turn.
                if new_ids and new_ids[-1] in eos_ids:
                    new_ids = new_ids[:-1]
                    new_lps = new_lps[:-1] if new_lps is not None else None
                _append(traj, new_ids, generated=True, logprobs=new_lps)
                _append(traj, tokenizer(INVALID_ACTION_MSG, add_special_tokens=False)["input_ids"],
                        generated=False)
                next_active.append(i)

        if queries:
            for i, docs in zip(searchers, search_fn(queries)):
                docs_ids = tokenizer(docs.strip(), add_special_tokens=False)["input_ids"]
                _append(trajs[i], info_open + docs_ids[:docs_budget] + info_close, generated=False)
                trajs[i].n_searches += 1
        active = next_active

    for traj in trajs:
        assert len(traj.response_ids) == len(traj.loss_mask) == len(traj.rollout_logprobs)
        if not traj.finish:
            traj.finish = "length"
        traj.response_text = tokenizer.decode(traj.response_ids, skip_special_tokens=True)
    return trajs